// Regenerate with: go run ./api/generate
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/pacificbelt30/codex-dock/pkg/cxd/localapi"
)

func main() {
	data, err := localapi.Schema()
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("api/local-v1/schema.json", data, 0644); err != nil {
		panic(err)
	}
	var schema struct {
		Defs map[string]map[string]any `json:"$defs"`
	}
	if err = json.Unmarshal(data, &schema); err != nil {
		panic(err)
	}
	keys := []string{}
	for k := range schema.Defs {
		if k != "Request" && k != "Response" {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("// Generated by go run ./api/generate; do not edit.\n")
	for _, k := range keys {
		d := schema.Defs[k]
		props, ok := d["properties"].(map[string]any)
		if !ok {
			continue
		}
		required := map[string]bool{}
		for _, v := range array(d["required"]) {
			required[stringValue(v)] = true
		}
		fmt.Fprintf(&b, "export interface %s {\n", k)
		names := []string{}
		for n := range props {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			optional := "?"
			if required[n] {
				optional = ""
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", n, optional, tsType(object(props[n])))
		}
		b.WriteString("}\n")
	}
	var root map[string]any
	if err = json.Unmarshal(data, &root); err != nil {
		panic(err)
	}
	b.WriteString("export interface MethodParams {\n")
	for _, request := range array(object(object(root["$defs"])["Request"])["oneOf"]) {
		properties := object(object(request)["properties"])
		fmt.Fprintf(&b, "  %s: %s;\n", object(properties["method"])["const"], tsType(object(properties["params"])))
	}
	b.WriteString("}\nexport interface MethodResults {\n")
	for _, result := range array(object(root["x-oaiso"])["results"]) {
		v := object(result)
		fmt.Fprintf(&b, "  %s: %s;\n", v["method"], tsType(object(v["result"])))
	}
	b.WriteString("}\n")
	if err = os.WriteFile("sdk/typescript/src/types.ts", []byte(b.String()), 0644); err != nil {
		panic(err)
	}
}
func tsType(s map[string]any) string {
	if ref, ok := s["$ref"].(string); ok {
		return strings.TrimPrefix(ref, "#/$defs/")
	}
	if v, ok := s["anyOf"].([]any); ok {
		a := []string{}
		for _, x := range v {
			a = append(a, tsType(object(x)))
		}
		return strings.Join(a, " | ")
	}
	if a, ok := s["type"].([]any); ok {
		v := []string{}
		for _, t := range a {
			copy := map[string]any{}
			for k, x := range s {
				copy[k] = x
			}
			copy["type"] = t
			v = append(v, tsType(copy))
		}
		return strings.Join(v, " | ")
	}
	switch s["type"] {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		return "(" + tsType(object(s["items"])) + ")[]"
	case "object":
		if a, ok := s["additionalProperties"].(map[string]any); ok {
			return "Record<string, " + tsType(a) + ">"
		}
		return "Record<string, never>"
	}
	return "unknown"
}

func object(v any) map[string]any {
	m, ok := v.(map[string]any)
	if !ok {
		panic("expected generated schema object")
	}
	return m
}
func array(v any) []any {
	a, ok := v.([]any)
	if !ok {
		panic("expected generated schema array")
	}
	return a
}
func stringValue(v any) string {
	s, ok := v.(string)
	if !ok {
		panic("expected generated schema string")
	}
	return s
}
